/**
 * Icon component for web that renders SVG icons with theme integration.
 *
 * @example
 * // Basic usage
 * <Icon name="home" size="md" color="primary" />
 *
 * @example
 * // Custom color and accessibility
 * <Icon
 *   name="check-circle"
 *   color="#22C55E"
 *   accessibilityLabel="Success indicator"
 * />
 */
export function Icon({
  name,
  size = 'md',
  color,
  family: _family = 'material',
  accessibilityLabel,
  decorative = false,
  style,
  testID,
}: IconProps): React.ReactElement {
  const { theme } = useTheme();
  const iconSize = iconSizes[size];
  const iconColor = getColorValue(color, theme.colors);

  // Look up the icon path
  const iconPath = iconPaths[name];

  return (
    <View
      style={[{ width: iconSize, height: iconSize }, style]}
      testID={testID}
      accessibilityLabel={decorative ? undefined : accessibilityLabel}
      accessibilityRole={decorative ? undefined : 'image'}
      // @ts-ignore - web specific
      aria-hidden={decorative}
    >
      {iconPath ? (
        <SvgIcon
          path={iconPath}
          size={iconSize}
          color={iconColor}
          accessibilityLabel={accessibilityLabel}
          decorative={decorative}
        />
      ) : (
        <FallbackIcon size={iconSize} color={iconColor} />
      )}
    </View>
  );
}

